/* ==========================================================================
   Lucide icons, inline.

   The redesign replaces every emoji with a stroke icon. Emoji were the wrong
   tool here for two reasons: they render differently on every platform — the
   compass that anchors the brand looked like a different object on Android
   than on iOS — and they cannot take the page's colour, so they could not
   carry state the way an active tab or a verdict needs to.

   Inlined as path data rather than loaded from a CDN. The site's
   Content-Security-Policy allows scripts only from self and googletagmanager,
   and an icon font would be a second render-blocking request for something
   that amounts to a few hundred bytes of path data.

   Only the icons this product actually uses are here. Adding one means
   copying its path data from lucide.dev — do not pull in the whole set.
   ========================================================================== */

