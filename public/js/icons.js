/**
 * Render one icon.
 *
 * `size` is the rendered box in px; the viewBox stays 24 so stroke weight
 * scales with it. `aria-hidden` by default — an icon beside a label is
 * decoration, and announcing it twice is worse than not announcing it. Pass
 * a `label` only when the icon stands alone as the control.
 */
export function icon(name, { size = 20, stroke = 2, cls = '', label = '' } = {}) {
  const d = PATHS[name];
  if (!d) return '';
  return `<svg class="ic ${cls}" width="${size}" height="${size}" viewBox="0 0 24 24"
    fill="none" stroke="currentColor" stroke-width="${stroke}"
    stroke-linecap="round" stroke-linejoin="round"
    ${label ? `role="img" aria-label="${label}"` : 'aria-hidden="true"'}>${d}</svg>`;
}

